/* ===== Inventory Intelligence Platform - authentication UI (jQuery) ===== */

/* ---------------------------------------------------------------
   PLACEHOLDER API FUNCTIONS

   Login:
   data = { email, password, remember }

   Signup:
   data = { fullName, companyName, email, password, terms, csrf_token }
---------------------------------------------------------------- */

/* ---------------------------------------------------------------
   LOGIN
---------------------------------------------------------------- */

function handleLogin(data) {
  return new Promise(function (resolve, reject) {

    $.ajax({
      url: 'api/v1/auth/login.php',
      method: 'POST',
      contentType: 'application/json',
      dataType: 'json',

      /*
       * CSRF protection.
       *
       * The token is generated by login.php and stored
       * in the login form's hidden input.
       *
       * It is sent in the X-CSRF-Token request header.
       */
      headers: {
        'X-CSRF-Token': data.csrf_token
      },

      data: JSON.stringify({
        email: data.email,
        password: data.password,
        remember: data.remember,
        csrf_token: data.csrf_token
      }),

      success: function (response) {

        if (response && response.success) {
          resolve(response);
          return;
        }

        var message = 'Unable to sign in.';

        if (
          response &&
          response.error &&
          response.error.message
        ) {
          message = response.error.message;
        }

        reject(new Error(message));
      },

      error: function (xhr) {

        var message =
          'Unable to sign in. Please try again.';

        if (
          xhr.responseJSON &&
          xhr.responseJSON.error &&
          xhr.responseJSON.error.message
        ) {
          message =
            xhr.responseJSON.error.message;
        }

        reject(new Error(message));
      }
    });

  });
}

/* ---------------------------------------------------------------
   SIGNUP
---------------------------------------------------------------- */

function handleSignup(data) {
  return new Promise(function (resolve, reject) {

    $.ajax({
      url: 'api/v1/companies/',
      method: 'POST',
      contentType: 'application/json',
      dataType: 'json',

      /*
       * CSRF protection.
       *
       * The token is generated by signup.php and stored
       * in the signup form's hidden input.
       *
       * It is sent in the X-CSRF-Token request header.
       */
      headers: {
        'X-CSRF-Token': data.csrf_token
      },

      data: JSON.stringify({
        fullName: data.fullName,
        companyName: data.companyName,
        email: data.email,
        password: data.password,
        terms: data.terms,
        csrf_token: data.csrf_token
      }),

      success: function (response) {

        if (response && response.success) {
          resolve(response);
          return;
        }

        reject(
          new Error(
            response &&
            response.error &&
            response.error.message
              ? response.error.message
              : 'Unable to create the account.'
          )
        );
      },

      error: function (xhr) {

        var message =
          'Unable to create the account. Please try again.';

        if (
          xhr.responseJSON &&
          xhr.responseJSON.error &&
          xhr.responseJSON.error.message
        ) {
          message = xhr.responseJSON.error.message;
        }

        reject(new Error(message));
      }
    });

  });
}


/* ---------------------------------------------------------------
   AUTH SUCCESS HANDLER
---------------------------------------------------------------- */

function onAuthSuccess(formName, result) {

  if (formName === 'signup') {
    window.location.href = 'dashboard.php';
    return;
  }

  window.location.href = 'dashboard.php';
}


$(function () {

  var MIN_PASSWORD = 8;
  var EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;


  /* ---------------------------------------------------------------
     VALIDATION RULES

     Each rule returns:
     - ''      = valid
     - message = invalid
  ---------------------------------------------------------------- */

  var rules = {

    /* Email */
    email: function (value) {

      value = $.trim(value);

      if (!value) {
        return 'Enter your email address.';
      }

      if (!EMAIL_PATTERN.test(value)) {
        return 'Enter a valid email, like name@company.com.';
      }

      return '';
    },


    /* Full name */
    name: function (value) {

      value = $.trim(value);

      if (value.length < 2) {
        return 'Enter your full name.';
      }

      return '';
    },


    /* Company / Workspace name
       Specification: 2–150 characters */
    companyName: function (value) {

      value = $.trim(value);

      if (!value) {
        return 'Enter your company name.';
      }

      if (value.length < 2) {
        return 'Company name must be at least 2 characters.';
      }

      if (value.length > 150) {
        return 'Company name cannot exceed 150 characters.';
      }

      return '';
    },


    /* Login password */
    loginPassword: function (value) {
      return value ? '' : 'Enter your password.';
    },


    /* Signup password */
    password: function (value) {

      if (!value) {
        return 'Create a password.';
      }

      if (value.length < MIN_PASSWORD) {
        return 'Use at least ' + MIN_PASSWORD + ' characters.';
      }

      return '';
    },


    /* Confirm password */
    confirm: function (value, $form) {

      if (!value) {
        return 'Confirm your password.';
      }

      if (value !== $form.find('[name="password"]').val()) {
        return 'Passwords don’t match.';
      }

      return '';
    },


    /* Terms */
    terms: function (checked) {
      return checked ? '' : 'Accept the terms to create an account.';
    }
  };


  /* ---------------------------------------------------------------
     VALIDATE ONE FIELD
  ---------------------------------------------------------------- */

  function validateField($input) {

    var rule = rules[$input.data('rule')];

    if (!rule) {
      return true;
    }

    var value = $input.is(':checkbox')
      ? $input.is(':checked')
      : $input.val();

    var message = rule(
      value,
      $input.closest('form')
    );

    $input.attr(
      'aria-invalid',
      message ? 'true' : 'false'
    );

    $input
      .closest('.field')
      .find('.field-error')
      .text(message);

    return !message;
  }


  /* ---------------------------------------------------------------
     VALIDATE COMPLETE FORM

     Returns first invalid input or null.
  ---------------------------------------------------------------- */

  function validateForm($form) {

    var firstInvalid = null;

    $form.find('[data-rule]').each(function () {

      if (!validateField($(this)) && !firstInvalid) {
        firstInvalid = $(this);
      }

    });

    return firstInvalid;
  }


  /* ---------------------------------------------------------------
     UI HELPERS
  ---------------------------------------------------------------- */

  function showAlert($form, title, text) {

    var $alert = $form.find('.alert');

    $alert.find('.alert-title').text(title);
    $alert.find('.alert-text').text(text);

    $alert.prop('hidden', false);
  }


  function hideAlert($form) {

    $form
      .find('.alert')
      .prop('hidden', true);
  }


  function setLoading($form, isLoading) {

    var $button = $form.find('.btn');
    var $label = $button.find('.btn-label');

    $button
      .prop('disabled', isLoading)
      .attr('aria-busy', isLoading);

    $label.text(
      isLoading
        ? $label.data('loading')
        : $label.data('default')
    );

    $form
      .find('.toggle')
      .prop('disabled', isLoading);
  }


  /* ---------------------------------------------------------------
     PASSWORD SHOW / HIDE
  ---------------------------------------------------------------- */

  $('.toggle').on('click', function () {

    var $button = $(this);

    var $input = $button
      .closest('.control')
      .find('input');

    var show = $input.attr('type') === 'password';

    $input.attr(
      'type',
      show ? 'text' : 'password'
    );

    $button.attr({
      'aria-pressed': show,
      'aria-label': show
        ? 'Hide password'
        : 'Show password'
    });
  });


  /* ---------------------------------------------------------------
     BLUR VALIDATION
  ---------------------------------------------------------------- */

  $('.auth-form').on(
    'blur',
    '[data-rule]',
    function () {

      var $input = $(this);

      if (
        $input.val() ||
        $input.attr('aria-invalid') === 'true'
      ) {
        validateField($input);
      }
    }
  );


  /* ---------------------------------------------------------------
     LIVE VALIDATION
  ---------------------------------------------------------------- */

  $('.auth-form').on(
    'input',
    '[data-rule]',
    function () {

      var $input = $(this);
      var $form = $input.closest('form');

      if (
        $input.attr('aria-invalid') === 'true'
      ) {
        validateField($input);
      }

      /* Keep confirm password synchronized */
      if (
        $input.attr('name') === 'password'
      ) {

        var $confirm = $form.find(
          '[name="confirmPassword"]'
        );

        if ($confirm.val()) {
          validateField($confirm);
        }
      }

      hideAlert($form);
    }
  );


  /* ---------------------------------------------------------------
     CHECKBOX VALIDATION
  ---------------------------------------------------------------- */

  $('.auth-form').on(
    'change',
    '[type="checkbox"][data-rule]',
    function () {

      validateField($(this));
    }
  );


  /* ---------------------------------------------------------------
     PLACEHOLDER LINKS

     Terms / Privacy / Forgot Password are UI-only for now.
  ---------------------------------------------------------------- */

  $('.ui-only').on(
    'click',
    function (event) {

      event.preventDefault();
    }
  );


  /* ---------------------------------------------------------------
     FORM SUBMIT
  ---------------------------------------------------------------- */

  $('.auth-form').on(
    'submit',
    function (event) {

      event.preventDefault();

      var $form = $(this);

      var formName = $form.data('form');

      hideAlert($form);


      /* -----------------------------------------
         Validate form
      ----------------------------------------- */

      var $firstInvalid = validateForm($form);

      if ($firstInvalid) {

        showAlert(
          $form,
          'Check the highlighted fields.',
          'Fix the errors below and try again.'
        );

        $firstInvalid.trigger('focus');

        return;
      }


      /* -----------------------------------------
         Collect form data
      ----------------------------------------- */

      var data;


      /* LOGIN */
       if (formName === 'login') {

        data = {

          email: $.trim(
            $form.find('[name="email"]').val()
          ),

          password:
            $form.find('[name="password"]').val(),

          remember:
            $form
              .find('[name="remember"]')
              .is(':checked'),

          csrf_token:
            $form
              .find('input[name="csrf_token"]')
              .val()
        };

      }


      /* SIGNUP */
      else {

        data = {

          fullName: $.trim(
            $form.find('[name="fullName"]').val()
          ),

          companyName: $.trim(
            $form.find('[name="companyName"]').val()
          ),

          email: $.trim(
            $form.find('[name="email"]').val()
          ),

          password:
            $form.find('[name="password"]').val(),

          terms:
            $form
              .find('[name="terms"]')
              .is(':checked'),

          /*
           * CSRF token generated by signup.php.
           */
          csrf_token:
            $form
              .find('input[name="csrf_token"]')
              .val()
        };
      }


      /* -----------------------------------------
         Start loading state
      ----------------------------------------- */

      setLoading($form, true);


      /* -----------------------------------------
         Call appropriate auth handler
      ----------------------------------------- */

      var request =
        (formName === 'login')
          ? handleLogin(data)
          : handleSignup(data);


      /* -----------------------------------------
         Handle response
      ----------------------------------------- */

      request

        .then(function (result) {

          onAuthSuccess(
            formName,
            result
          );
        })

        .catch(function (error) {

          var title =
            (formName === 'login')
              ? 'Couldn’t sign you in.'
              : 'Couldn’t create your account.';

          showAlert(
            $form,
            title,
            error && error.message
              ? error.message
              : 'Something went wrong. Try again.'
          );
        })

        .finally(function () {

          setLoading(
            $form,
            false
          );
        });
    }
  );

});